def select(with_stack: bool, stack_only: bool, only: list[str]) -> list[tuple]:
    """The mutants to run: the offline ones, with the stack's too (with_stack), or the stack's alone (stack_only); of
    the files named in only, when it names any."""
    with_stack = with_stack or stack_only
    return [m for m in MUTANTS if (with_stack or not m[4]) and (m[4] or not stack_only) and (not only or m[1] in only)]


def run_tests(work: Path, python: str, integration: bool) -> subprocess.CompletedProcess:
    args = [python, "-m", "pytest", "-q", "-x", "-p", "no:cacheprovider"]
    if integration:
        args += ["-m", "integration"]
    # No .pyc written: two mutants of one file, of the same size, written within a second, could share a stale one.
    env = {"PYTHONPATH": str(work / "src"), "PATH": "/usr/bin:/bin", "HOME": str(Path.home()), "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        return subprocess.run(args, cwd=work, env=env, capture_output=True, text=True, timeout=600)
    except subprocess.TimeoutExpired:  # a suite that hangs under a mutant did not pass: the mutant is caught
        return subprocess.CompletedProcess(args, 1, "FAILED (the tests did not end within 600 s)", "")


USAGE = "usage: python scripts/mutation_check.py REPO WORKDIR [--with-stack | --stack-only] [--only FILE ...]"


def main() -> int:
    if "-h" in sys.argv[1:] or "--help" in sys.argv[1:]:
        print(__doc__)
        return 0
    if len(sys.argv) < 3 or any(arg.startswith("-") for arg in sys.argv[1:3]):  # REPO and WORKDIR come first
        print(USAGE, file=sys.stderr)
        return 2
    repo, work = Path(sys.argv[1]), Path(sys.argv[2])
    stack_only = "--stack-only" in sys.argv  # week 5: the stack's mutants alone, once the offline ones have run
    with_stack = stack_only or "--with-stack" in sys.argv
    only = sys.argv[sys.argv.index("--only") + 1 :] if "--only" in sys.argv else []
    unknown = sorted(set(only) - {m[1] for m in MUTANTS})
    if unknown:
        print(f"no mutants for: {', '.join(unknown)}")
        return 2
    python = str(repo / ".venv" / "bin" / "python")
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    # evidence: a test replays the first live run of the loop from its recording (week 3, item 3). scripts: a test
    # calls this runner's own command line (week 5). deploy: a test checks the kind manifests against compose.yaml,
    # and some mutants break them (week 5, item 5). .gitignore: a test reads it.
    for item in ("src", "tests", "docker", "deploy", "evidence", "scripts", "compose.yaml", "pyproject.toml", "Makefile",
                 ".gitignore"):
        src = repo / item
        (shutil.copytree if src.is_dir() else shutil.copy2)(src, work / item)

    check = subprocess.run(
        [python, "-c", "import klaxon, sys; print(klaxon.__file__)"],
        env={"PYTHONPATH": str(work / "src")}, capture_output=True, text=True,
    )
    assert str(work) in check.stdout, f"the copy is not the code under test: {check.stdout}"

    selected = select(with_stack, stack_only, only)
    # A mutant that does not compile would be "caught" by any test that imports its module: say so, and stop.
    broken = []
    for name, file, old, new, _ in selected:
        if file.endswith(".py"):
            try:
                compile((work / file).read_text().replace(old, new), file, "exec")
            except SyntaxError as exc:
                broken.append(f"{name} ({type(exc).__name__}: {exc.msg}, line {exc.lineno})")
    if broken:
        print("mutants that do not compile:\n  " + "\n  ".join(broken))
        return 2
    for integration in sorted({m[4] for m in selected}):
        baseline = run_tests(work, python, integration)
        if baseline.returncode != 0:
            print(f"baseline FAILED ({'integration' if integration else 'offline'}):\n{baseline.stdout[-3000:]}")
            return 2
        print(f"baseline passes ({'integration' if integration else 'offline'})")

    survived = []
    for name, file, old, new, integration in selected:
        path = work / file
        original = path.read_text()
        assert original.count(old) == 1, f"{name}: the text to break is not found exactly once in {file}"
        path.write_text(original.replace(old, new))
        try:
            result = run_tests(work, python, integration)
        finally:
            path.write_text(original)
        killed = result.returncode != 0
        failing = next((line for line in result.stdout.splitlines() if line.startswith("FAILED")), "")
        print(f"{'caught  ' if killed else 'SURVIVED'}  {name}  {failing[:150]}")
        if not killed:
            survived.append(name)
    print(f"\n{len(selected) - len(survived)} of {len(selected)} deliberate breaks caught")
    return 1 if survived else 0


if __name__ == "__main__":
    raise SystemExit(main())
